(function (Game) {
  // Real-time timers deliberately do not accelerate from click-granted game time.
  Game.Automation = {
    definition: function (id) { return Game.CONFIG.AUTOMATION.buyers.find(function (buyer) { return buyer.id === id; }); },
    unlocked: function (id) { const buyer=this.definition(id);return !!buyer && Game.Progression.hasSkill(buyer.skill); },
    interval: function (id) { return (50 - 4 * Game.player.automation.buyers[id].level) / 10; },
    active: function (id) { return this.unlocked(id) && !!Game.player.settings.autoBuyers[id]; },
    setEnabled: function (id, enabled) {
      if (!this.definition(id) || enabled && !this.unlocked(id)) return false;
      Game.player.settings.autoBuyers[id]=Number(!!enabled);
      Game.player.automation.buyers[id].elapsed=0;
      return true;
    },
    setAll: function (enabled) {
      Game.CONFIG.AUTOMATION.buyers.forEach(function (buyer) { Game.Automation.setEnabled(buyer.id,enabled); });
    },
    remaining: function () {
      return Game.CONFIG.AUTOMATION.buyers.reduce(function (next,buyer) {
        return Game.Automation.active(buyer.id) ? Math.min(next,Math.max(0,Game.Automation.interval(buyer.id)-Game.player.automation.buyers[buyer.id].elapsed)) : next;
      },Infinity);
    },
    advance: function (seconds) {
      Game.CONFIG.AUTOMATION.buyers.forEach(function (buyer) {
        const state=Game.player.automation.buyers[buyer.id];
        state.elapsed=Game.Automation.active(buyer.id) ? Math.round((state.elapsed+seconds)*1e9)/1e9 : 0;
      });
    },
    resolve: function () {
      // Stable priority: Gen 1 through Gen 7, then Condense. No banked attempts.
      Game.CONFIG.AUTOMATION.buyers.forEach(function (buyer) {
        const state=Game.player.automation.buyers[buyer.id];
        if (!Game.Automation.active(buyer.id) || state.elapsed+1e-9<Game.Automation.interval(buyer.id)) return;
        state.elapsed=0;
        if (buyer.id === 'condense') Game.Prestige.condense(true);
        else Game.Energy.buyGenerator(buyer.id,1);
      });
    },
    preserve: function (old,fresh) {
      // Challenge mastery survives both Condense and respec; timers start fresh.
      Game.CONFIG.AUTOMATION.buyers.forEach(function (buyer) {
        const state=old.automation.buyers[buyer.id];
        fresh.automation.buyers[buyer.id]={level:state.level,board:state.board,moves:state.moves,elapsed:0};
      });
    }
  };

  // Phase-alignment puzzles. A legal pulse flips the chosen cell and adjacent
  // cells. Boards are generated by legal pulses, so every level is solvable.
  // All arithmetic is bounded to 25 bits; no polling or background solver.
  const cache=new Map();
  Game.Challenges = {
    puzzle: function (id,level) {
      const key=id+':'+level;
      if (cache.has(key)) return cache.get(key);
      const index=Game.CONFIG.AUTOMATION.buyers.findIndex(function (buyer) { return buyer.id===id; });
      const size=level<3 ? 3 : level<7 ? 4 : 5, count=size*size;
      const masks=Array.from({length:count},function (_,cell) {
        const row=Math.floor(cell/size), col=cell%size;
        let mask=1<<cell;
        [[-1,0],[1,0],[0,-1],[0,1]].forEach(function (step) {
          const r=row+step[0], c=col+step[1];if(r>=0 && r<size && c>=0 && c<size) mask^=1<<(r*size+c);
        });
        return mask;
      });
      let seed=0x6d2b79f5 ^ ((index+1)*7919) ^ ((level+1)*104729);
      const order=Array.from({length:count},function (_,i) { return i; });
      for(let i=count-1;i>0;i--) { seed^=seed<<13;seed^=seed>>>17;seed^=seed<<5;const j=(seed>>>0)%(i+1), item=order[i];order[i]=order[j];order[j]=item; }
      // A seeded, increasingly layered interference pattern for each buyer.
      let board=0;
      order.slice(0,Math.min(count-1,level+2)).forEach(function (cell) { board^=masks[cell]; });
      if (!board) board=masks[order[0]];
      const puzzle={size:size,masks:masks,initial:board};cache.set(key,puzzle);return puzzle;
    },
    board: function (id) { const state=Game.player.automation.buyers[id];return state.board || this.puzzle(id,state.level).initial; },
    pulse: function (id,cell) {
      const state=Game.player.automation.buyers[id];
      if (!Game.Automation.unlocked(id) || state.level>=10) return false;
      const puzzle=this.puzzle(id,state.level);
      if (!Number.isInteger(cell) || cell<0 || cell>=puzzle.masks.length) return false;
      state.board=this.board(id)^puzzle.masks[cell];state.moves=Math.min(Number.MAX_SAFE_INTEGER,state.moves+1);
      if (state.board===0) {
        state.level++;state.moves=0;
        // Preserve the fraction of the automation cycle when its speed improves.
        state.elapsed=state.elapsed*Game.Automation.interval(id)/(Game.Automation.interval(id)+.4);
        if (Game.Audio) Game.Audio.play('perk');
      }
      Game.Save.save();return true;
    },
    reset: function (id) {
      if (!Game.Automation.unlocked(id)) return false;
      const state=Game.player.automation.buyers[id];state.board=0;state.moves=0;Game.Save.save();return true;
    }
  };
})(window.CosmicIdle);
